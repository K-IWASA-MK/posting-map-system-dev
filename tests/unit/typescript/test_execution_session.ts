function assert(condition: boolean, message: string) {
  if (!condition) {
    throw new Error(`[Assertion Failure] ${message}`);
  }
}

const sleep = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

// Custom mock ID provider
class MockSessionIdProvider implements ISessionIdProvider {
  public generateSessionId(): string {
    return 'session-mock-12345';
  }
}

// ==============================================================================
// Test 1: Session Creation, Activation and Status Transitions
// ==============================================================================
async function testSessionActivationAndMetrics() {
  console.log('[Test 1] Session activation and metrics starting...');
  const runtime = new LauncherExecutionRuntime();
  const registry = new LauncherRuntimeRegistry();
  const idProvider = new MockSessionIdProvider();
  const manager = new ExecutionSessionManager(registry, idProvider);

  const mockAllow: LauncherResult = {
    success: true,
    projectId: 'posting-map',
    mode: 'development',
    decision: 'allow',
    reasons: [],
    errorCodes: [],
    warnings: []
  };

  const proc = await runtime.execute(mockAllow, {
    args: ['-e', 'console.log("line-1"); console.log("line-2");']
  });

  const session = manager.createSession(proc, 'req-abc');

  try {
    assert(session.sessionId === 'session-mock-12345', 'Session ID should be generated by mock provider');
    assert(session.status === 'active', 'Session status should be active after manager creation');
    assert(registry.count() === 1, 'Process should be registered');

    // Wait for process stdout streams to pipe and exit
    await new Promise<void>((resolve) => {
      session.process.onExit(() => resolve());
    });

    await sleep(100);

    // Verify stdout lines metrics collected
    assert(session.metrics.stdoutLines === 2, `Expected 2 stdout lines, got: ${session.metrics.stdoutLines}`);
    assert(session.status === 'completed', `Expected completed status, got: ${session.status}`);
    assert(session.exitCode === 0, 'Expected exit code 0');

    console.log('[Test 1] Session activation and metrics: PASSED');
  } finally {
    await session.stop();
  }
}

