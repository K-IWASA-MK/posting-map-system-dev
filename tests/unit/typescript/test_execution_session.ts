// Test 3: Snapshots and Factory Conversion
// ==============================================================================
async function testSnapshotFactory() {
  console.log('[Test 3] Session snapshot factory starting...');
  const runtime = new LauncherExecutionRuntime();
  const registry = new LauncherRuntimeRegistry();
  const idProvider = new MockSessionIdProvider();
  const manager = new ExecutionSessionManager(registry, idProvider);

  const mockAllow: LauncherResult = {
    success: true,
    projectId: 'posting-map',
    mode: 'development',
    decision: 'allow',
    reasons: [],
    errorCodes: [],
    warnings: []
  };

  const proc = await runtime.execute(mockAllow);
  const session = manager.createSession(proc, 'req-999');

  try {
    // 1. Snapshot running status
    const runningSnapshot = ExecutionResultFactory.createSnapshot(session);
    assert(runningSnapshot.status === 'running', 'Expected running snapshot status');
    assert(runningSnapshot.projectId === 'posting-map', 'Project ID mismatch');
    assert(runningSnapshot.requestId === 'req-999', 'Request ID mismatch');
    assert(runningSnapshot.pid === proc.pid, 'PID mismatch');

    // 2. Snapshot stopped status
    await session.stop();
    const stoppedSnapshot = ExecutionResultFactory.createSnapshot(session);
    assert(stoppedSnapshot.status === 'stopped', 'Expected stopped snapshot status');

    console.log('[Test 3] Session snapshot factory: PASSED');
  } finally {
    await session.stop();
  }
}

