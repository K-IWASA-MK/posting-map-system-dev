// Test 4: Session Manager Termination & Registry Sync
// ==============================================================================
async function testManagerTermination() {
  console.log('[Test 4] Manager termination and registry sync starting...');
  const runtime = new LauncherExecutionRuntime();
  const registry = new LauncherRuntimeRegistry();
  const idProvider = new MockSessionIdProvider();
  const manager = new ExecutionSessionManager(registry, idProvider);

  const mockAllow: LauncherResult = {
    success: true,
    projectId: 'posting-map',
    mode: 'development',
    decision: 'allow',
    reasons: [],
    errorCodes: [],
    warnings: []
  };

  const proc = await runtime.execute(mockAllow);
  const session = manager.createSession(proc);

  try {
    assert(registry.count() === 1, 'Registry should have 1 active process');
    assert(manager.listSessions().length === 1, 'Manager should track 1 session');

    await manager.terminateSession(session.sessionId);
    assert(session.status === 'terminated', `Expected terminated session status, got: ${session.status}`);
    assert(registry.count() === 0, 'Registry should be empty after session termination');

    console.log('[Test 4] Manager termination and registry sync: PASSED');
  } finally {
    await session.stop();
  }
}

